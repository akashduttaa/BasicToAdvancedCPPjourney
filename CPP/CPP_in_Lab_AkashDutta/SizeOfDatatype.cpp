#include<iostream>
using namespace std ;
int main(){

    cout<<"The Size of Char :" << sizeof(char) << "byte" << '\n';
    cout<<"The Size of Int :" << sizeof(int) << "byte" << '\n';
    cout<<"The Size of Long Int :" << sizeof(long int) << "byte" << '\n';
    cout<<"The Size of Short Int :" << sizeof(short int) << "byte" << '\n';
    cout<<"The Size of Signed Long Int :" << sizeof(signed long int) << "byte" << '\n';
    cout<<"The Size of Unsigned Long Int :" << sizeof(unsigned long int) << "byte" << '\n';
    cout<<"The Size of Float :" << sizeof(float) << "byte" << '\n';
    cout<<"The Size of Double :" << sizeof(double) << "byte" << '\n';
    cout<<"The Size of Boolean :" << sizeof(bool) << "byte" << '\n';


    return 0 ;
}